//! Generated CI test harness for architecture invariants.
//!
//! `export_contracts` compiles every active contract into a Rust test that
//! runs `ast-grep scan` against the codebase, so `cargo test` enforces the
//! store's invariants without UMA in the loop. Fail-closed by design: a
//! missing engine or a non-empty findings list must fail the build, never
//! pass silently.

use std::path::PathBuf;

use crate::store::Store;

/// One verifiable rule: (fact id, sanitized title, rule file, title).
pub type HarnessCase = (String, String, String, String);

/// One unverifiable rule: (fact id, sanitized title, title, reason).
pub type UnverifiableCase = (String, String, String, String);

/// Sanitizes a fact title for a generated Rust identifier/comment.
pub fn safe_title_of(title: &str) -> String {
    title
        .chars()
        .map(|c| {
            if c.is_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// Writes `tests/architecture_invariants.rs` at the git root and returns its
/// path. Every verifiable rule becomes an ast-grep scan assertion; every
/// unverifiable rule (SPAI-055 blind-spot pattern) becomes a test that FAILS
/// loudly — the alternative is an invariant that silently protects nothing.
pub fn write_harness(
    test_cases: &[HarnessCase],
    unverifiable_cases: &[UnverifiableCase],
) -> Option<PathBuf> {
    let git_root = Store::find_git_root().ok()?;
    let tests_dir = git_root.join("tests");
    if !(tests_dir.exists() || git_root.join("Cargo.toml").exists()) {
        return None;
    }
    let _ = std::fs::create_dir_all(&tests_dir);
    let harness_path = tests_dir.join("architecture_invariants.rs");

    let mut code = String::new();
    code.push_str("//! Generated by UMA (Universal Memory Architecture).\n");
    code.push_str("//! Invariants compiled directly from active memory decisions.\n\n");

    for (id, safe_title, rule_file, title) in test_cases {
        // Sanitize the title for a line comment: a newline would inject
        // arbitrary Rust into the generated harness and run under
        // `cargo test`. Collapse every control character and newline.
        let safe_comment: String = sanitize_comment(title);
        code.push_str(&format!(
            "#[test]\nfn invariant_{}_{}() {{\n",
            id[..8].to_lowercase(),
            safe_title
        ));
        code.push_str(&format!("    // Memory Decision: {}\n", safe_comment));
        let test_body = format!(
            r#"    let ast_grep = if cfg!(windows) {{ "ast-grep.exe" }} else {{ "ast-grep" }};
    // Fail CLOSED: a missing engine must never let the invariant pass silently,
    // and `sg` is deliberately NOT used as a fallback (on Unix it is
    // shadow-utils' setgid tool, not ast-grep).
    let output = std::process::Command::new(ast_grep)
        .args(["scan", "--json=compact", "--rule", ".uma/contracts/{rule_file}"])
        .output()
        .expect("ast-grep is required to verify architecture invariants (fail-closed)");
    let findings = String::from_utf8_lossy(&output.stdout);
    let findings = findings.trim();
    assert!(
        findings.is_empty() || findings == "[]",
        "Architecture invariant [{id}] violated!\n{{findings}}"
    );
"#,
            rule_file = rule_file,
            id = id,
        );
        code.push_str(&test_body);
        code.push_str("}\n\n");
    }

    // SPAI-055: an unverifiable contract must FAIL in CI, loudly — the
    // alternative is an invariant that silently protects nothing.
    for (id, safe_title, title, reason) in unverifiable_cases {
        let safe_comment: String = sanitize_comment(title);
        code.push_str(&format!(
            "#[test]\nfn invariant_{}_{}() {{\n",
            id[..8].to_lowercase(),
            safe_title
        ));
        code.push_str(&format!("    // Memory Decision: {}\n", safe_comment));
        code.push_str(&format!(
            "    panic!(\"contract [{}] is UNVERIFIABLE and protects nothing: {}. Fix the pattern (SPAI-055).\");\n",
            id, reason
        ));
        code.push_str("}\n\n");
    }

    if std::fs::write(&harness_path, code).is_ok() {
        Some(harness_path)
    } else {
        None
    }
}

/// Collapses control characters (including newlines) to spaces.
fn sanitize_comment(title: &str) -> String {
    title
        .chars()
        .map(|c| {
            if c == '\n' || c == '\r' || c.is_control() {
                ' '
            } else {
                c
            }
        })
        .collect()
}
