/**
 * /uma dash tests — the detail half (Proposal 10 §13 delta).
 *
 * The detail pane is where the full record lives: status, validity window,
 * provenance, task links, the executable AST contract, skill templates, the
 * plasticity/saliency metadata and the supersession chain. Everything here is
 * pure string-in/string-out against recorded read/timeline fixtures.
 */

import assert from "node:assert/strict";
import { test } from "node:test";
import { renderChain, renderDetail, shortDate } from "../src/slices/dash/detail.ts";
import { parseChainJson } from "../src/slices/dash/data.ts";
import { fact, readFact, TIMELINE_JSON } from "./dash_fixtures.ts";

test("renderDetail: full view carries metadata and rendered body", () => {
  const html = renderDetail(
    fact({
      factType: "pattern",
      scope: "project:pi-uma",
      tags: ["a"],
      weight: 0.75,
      body: "### X\n\n**y**",
    }),
  );
  assert.ok(html.includes("PATTERN"));
  assert.ok(html.includes("project:pi-uma"));
  assert.ok(html.includes(">weight<"), "the metadata label is rendered");
  assert.ok(html.includes("0.75"), "the value is rendered");
  assert.ok(html.includes("#a"));
  assert.ok(html.includes("<h4>X</h4>"));
});

test("renderDetail: renders the whole record, not just title and body", () => {
  const html = renderDetail(readFact());
  // status + validity window
  assert.ok(html.includes("⚠ deprecated"), "a retired fact must say so");
  assert.ok(html.includes("since 2026-10-08 07:48"));
  assert.ok(html.includes("stale after 2026-12-31"));
  assert.ok(html.includes("until 2026-10-12 10:54"));
  // task links, navigation links, provenance, description
  assert.ok(html.includes("SPAI-007 SPAI-041"));
  assert.ok(html.includes("01M4DGCX9C5TDXFVMMTHT6TAE7"));
  assert.ok(html.includes("generated by pi-agent/1.1"));
  assert.ok(html.includes("human:operator"));
  assert.ok(html.includes("Superseded by the 2026-10 revision."));
  // plasticity + saliency
  assert.ok(html.includes("w 0.85"));
  assert.ok(html.includes("↑4"));
  assert.ok(html.includes("half-life 30d"));
  assert.ok(html.includes("shock 0.80"));
  assert.ok(html.includes("decay-immune"));
  // the executable contract, with its severity and pattern
  assert.ok(html.includes("executable contract"));
  assert.ok(html.includes("sev-deny"));
  assert.ok(html.includes("use crate::slices::$$$REST;"));
  assert.ok(html.includes("slices must NEVER import each other"));
  // body still rendered
  assert.ok(html.includes("<strong>VSA</strong>"));
});

test("renderDetail: a skill template is shown as data, never executed", () => {
  const html = renderDetail(
    fact({ factType: "skill", template: '{"command":"ls","args":["-la"]}' }),
  );
  assert.ok(html.includes("skill template"));
  assert.ok(html.includes("never executed"));
  assert.ok(html.includes("&quot;command&quot;"));
  assert.ok(!html.includes('{"command"'));
});

test("renderDetail: a contract is escaped, never injected", () => {
  const html = renderDetail(
    fact({
      contract: {
        engine: "ast-grep",
        severity: "warn",
        rule: { pattern: "<img src=x>", message: "<b>rule</b>" },
      },
    }),
  );
  assert.ok(!html.includes("<img"));
  assert.ok(html.includes("&lt;img src=x&gt;"));
  assert.ok(html.includes("sev-warn"));
  assert.ok(!html.includes("<b>rule</b>"));
});

test("renderDetail: a stable fact carries no deprecated warning", () => {
  const html = renderDetail(fact({ status: "stable" }));
  assert.ok(!html.includes("⚠"));
  assert.ok(html.includes("stable"));
});

test("renderChain: every revision is listed, navigable and the tip marked", () => {
  const chain = parseChainJson(TIMELINE_JSON);
  assert.ok(chain, "the recorded timeline must parse");
  const html = renderChain(chain);
  assert.ok(html.includes("history"));
  assert.ok(html.includes("2 revision(s)"));
  assert.ok(html.includes("← current"));
  assert.ok(html.includes('hx-get="/frag/fact/01M4D7S5YART7AGWN7RDSRNRM1"'));
  assert.ok(html.includes('hx-get="/frag/fact/01M4QW0BW1WWJRGPE7FZTPBBMN"'));
  assert.ok(html.includes("st-deprecated"));
  assert.ok(html.includes("st-stable"));
  assert.ok((html.match(/chain-row/g) ?? []).length >= 2);
});

test("renderChain: an empty chain renders nothing at all", () => {
  assert.equal(renderChain({ current: "x", length: 0, hasHistory: false, revisions: [] }), "");
  assert.equal(parseChainJson("[]"), undefined);
});

test("shortDate: formats engine timestamps and tolerates the unexpected", () => {
  assert.equal(shortDate("2026-10-12T10:54:47.195736+00:00"), "2026-10-12 10:54");
  assert.equal(shortDate("2026-12-31"), "2026-12-31");
  assert.equal(shortDate(undefined), undefined);
});
